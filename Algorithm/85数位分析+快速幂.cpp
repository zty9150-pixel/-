
/*
题目：E - D-Function
考点：数学规律、数位分析、快速幂、模运算

一、题意

D(n) 表示 n 的各位数字之和。

给定 l、r、k，求满足以下条件的整数 n 的数量：

    10^l <= n < 10^r
    D(k * n) == k * D(n)

答案对 mod = 1e9 + 7 取模。

二、核心性质：什么时候等号成立？

设 n 的各位数字为 d[i]。

例如：
    n = 123
    D(n) = 1 + 2 + 3 = 6

将 n 乘以 k，实际上相当于把每一位数字乘以 k。

如果每一位都满足：

    k * d[i] <= 9

那么每一位乘以 k 后都不会产生进位，因此：

    D(k * n) = k * D(n)

反过来，如果某一位满足：

    k * d[i] >= 10

那么该位乘以 k 时必然产生进位。
进位会使最终数位和严格减小，因此不满足等式。

所以，每一位数字必须满足：

    d[i] <= 9 / k

这里是整数除法，等价于：

    d[i] <= floor(9 / k)

注意：这里要求的是“不产生进位”，
不是只判断 n * k 的结果是否有某种特定形式。

三、重点：根据 k 的范围分析

每一位数字最大为 9，因此必须满足：

    k * d[i] <= 9

1. k = 1

    d[i] <= 9

所有十进制数字 0~9 都可以选择。
每一位有 10 种选择。

例如 n = 123：
    D(1 * 123) = 6
    1 * D(123) = 6

2. k = 2

    d[i] <= 4

每一位只能选择 0~4，共 5 种。

例如 n = 123 不合法，因为数字 2、3 虽然合法，
但如果某一位是 5~9，乘 2 就会产生进位。

3. k = 3

    d[i] <= 3

每一位只能选择 0~3，共 4 种。

4. k = 4

    d[i] <= 2

每一位只能选择 0~2，共 3 种。

5. 5 <= k <= 9

    floor(9 / k) = 1

每一位只能选择 0、1，共 2 种。

特别注意：
    k = 9 时，9 * 1 = 9，仍然合法。
所以 k = 9 并不是答案为 0。

6. k >= 10

    floor(9 / k) = 0

每一位只能选择 0。

但题目要求：
    n >= 10^l >= 1

所以 n 不可能全为 0，答案必然为 0。

这也是为什么需要特别注意 k >= 10 的情况。

四、统一公式

定义每一位的可选数字数量为 m：

    m = floor(9 / k) + 1

因为可选数字为：

    0, 1, 2, ..., floor(9 / k)

所以：

    k = 1       -> m = 10
    k = 2       -> m = 5
    k = 3       -> m = 4
    k = 4       -> m = 3
    5 <= k <= 9 -> m = 2
    k >= 10     -> m = 1

五、为什么答案是 m^r - m^l？

先考虑所有满足条件且满足 0 <= n < 10^r 的数。

将每个数看成长度为 r 的数字串，
不足 r 位就在前面补 0。

每一位有 m 种选择，因此总数为：

    m^r

但是题目要求：

    10^l <= n < 10^r

因此还需要排除：

    0 <= n < 10^l

这些数只有低 l 位可以自由选择，
更高位必须为 0，因此数量为：

    m^l

最终答案：

    ans = m^r - m^l

在模 mod 意义下：

    ans = (m^r - m^l + mod) % mod

注意：
这里不是简单地数有多少位，而是利用每一位
都有 m 种合法选择，通过乘法原理进行计数。

六、快速幂

由于：
    r <= 1e9
    测试组数 t <= 1e4

不能直接循环计算 m^r。

使用快速幂，在 O(log r) 时间内计算：

    qpow(m, r)
    qpow(m, l)

七、完整代码*/

#include <bits/stdc++.h>
using namespace std;
using ll = long long;

const ll mod = 1e9 + 7;

// 快速幂：计算 a^b % mod
ll qpow(ll a, ll b)
{
  ll ans = 1;

  while (b > 0)
  {
    if (b & 1)
      ans = ans * a % mod;

    a = a * a % mod;
    b >>= 1;
  }

  return ans;
}

void solve()
{
  ll l, r, k;
  cin >> l >> r >> k;

  // 每一位允许的数字：
  // 0 ~ floor(9 / k)
  // 因此可选数字总数为 floor(9 / k) + 1
  ll m = 9 / k + 1;

  // 所有满足条件且小于 10^r 的数
  ll ans_r = qpow(m, r);

  // 所有满足条件且小于 10^l 的数
  ll ans_l = qpow(m, l);

  // 通过区间减法得到 [10^l, 10^r) 内的数量
  ll ans = (ans_r - ans_l + mod) % mod;

  cout << ans << '\n';
}

int main()
{
  ios::sync_with_stdio(false);
  cin.tie(nullptr);

  int t;
  cin >> t;

  while (t--)
    solve();

  return 0;
}

/*
八、复杂度分析

每组测试：
    时间复杂度：O(log r)
    空间复杂度：O(1)

九、这道题最重要的思维

1. 从数位和相等入手，寻找“不能产生进位”的条件。
2. 利用 k * d <= 9 限制每一位数字。
3. 根据 k 的范围理解合法数字数量：
   k <= 9 时有非零数字可选；
   k >= 10 时只有 0，答案为 0。
4. 用乘法原理得到 m^r。
5. 用区间减法得到 m^r - m^l。
6. 指数很大时使用快速幂。

核心公式：

    m = floor(9 / k) + 1
    ans = (m^r - m^l + mod) % mod
*/

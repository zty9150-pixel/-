/*
============================================================
I. a-Good String
核心：前缀和 + 分治 + 递归求最小修改次数
============================================================

一、题意与性质

定义一个字符串为 c-good：
1. 当字符串长度为 1 时，字符必须为 c。
2. 当字符串长度大于 1 时：
   - 左半部分全部为 c，右半部分为 (c+1)-good；
   - 或右半部分全部为 c，左半部分为 (c+1)-good。

每次可以将一个字符修改成任意字符，求最少修改次数。

注意：
不能只贪心地选择当前 c 字符数量更多的一半。
因为另一半递归后的修改代价也会影响最终答案。

必须计算两种方案，取最小值。

------------------------------------------------------------
二、前缀和预处理
------------------------------------------------------------

pre[c][i]：
表示前 i 个字符中，字符 c 出现的次数。

pre[c][i] = pre[c][i-1] + (s[i] == c)

查询区间 [l,r] 中字符 c 的数量：

cnt = pre[c][r] - pre[c][l-1]

将整个区间修改为 c 的代价：

cost = 区间长度 - 字符 c 的数量

即：

cost = (r-l+1) - (pre[c][r]-pre[c][l-1])

利用前缀和，可以 O(1) 计算区间修改代价。

------------------------------------------------------------
三、DFS 状态设计
------------------------------------------------------------

dfs(l,r,c)：

表示将 s[l...r] 修改成 c-good 字符串的最小代价。

递归边界：

当 l == r 时：
只剩一个字符，判断它是否等于 c。

相等：不需要修改，返回 0。
不相等：需要修改一次，返回 1。

------------------------------------------------------------
四、状态转移
------------------------------------------------------------

令 mid = (l+r)/2。

方案一：
左半部分全部修改为 c；
右半部分递归变成 (c+1)-good。

cnt1 = 左半部分修改为 c 的代价

cost1 = cnt1 + dfs(mid+1,r,c+1)

方案二：
右半部分全部修改为 c；
左半部分递归变成 (c+1)-good。

cnt2 = 右半部分修改为 c 的代价

cost2 = cnt2 + dfs(l,mid,c+1)

最终答案：

dfs(l,r,c) = min(cost1,cost2)

注意：
两种方案是互斥的，不是同时修改左右两半。
每次只固定一半，另一半继续递归。

------------------------------------------------------------
五、复杂度分析
------------------------------------------------------------

前缀和预处理：
O(26*n)

DFS：
每个递归节点只进行 O(1) 的前缀和查询。

T(n) = 2*T(n/2) + O(1)

递归树共有 O(n) 个节点，因此 DFS 为 O(n)。

总时间复杂度：O(26*n)，即 O(n)。
空间复杂度：O(26*n)，递归栈 O(log n)。

------------------------------------------------------------
六、容易出错的地方
------------------------------------------------------------

1. 必须先写递归边界 if(l == r)。
2. 前缀和区间查询使用 pre[r]-pre[l-1]。
3. 修改代价 = 区间长度 - 目标字符数量。
4. 两种递归方案都要计算，不能直接贪心。
5. 字符 c 每深入一层递增一次。
6. 字符集使用 26 个字母，pre[26][N]。

============================================================
*/

#include <bits/stdc++.h>
using namespace std;

const int N = 2e5 + 10;

int pre[26][N];
string s;

int dfs(int l, int r, int c)
{
  // 递归边界：只剩一个字符
  if (l == r)
    return pre[c][r] - pre[c][l - 1] == 0;

  int mid = (l + r) >> 1;

  // 方案一：左半全部修改成 c，右半递归
  int cnt1 = (mid - l + 1) - (pre[c][mid] - pre[c][l - 1]);

  int cost1 = cnt1 + dfs(mid + 1, r, c + 1);

  // 方案二：右半全部修改成 c，左半递归
  int cnt2 = (r - mid) - (pre[c][r] - pre[c][mid]);

  int cost2 = cnt2 + dfs(l, mid, c + 1);

  return min(cost1, cost2);
}

void solve()
{
  int n;
  cin >> n >> s;

  s = ' ' + s;

  // 预处理 26 个字母的前缀和
  for (int c = 0; c < 26; ++c)
  {
    for (int i = 1; i <= n; ++i)
    {
      pre[c][i] = pre[c][i - 1] + (s[i] == c + 'a');
    }
  }

  cout << dfs(1, n, 0) << '\n';
}

/*
题目：Kevin and Binary Strings
考点：二进制字符串、贪心、字符串逐位比较
核心：固定第一个子串为整个字符串，枚举第二个子串的起点

一、为什么第一个子串选整个字符串？
1. s 以 '1' 开头，整个字符串对应的二进制数有 n 位。
2. 如果第一个子串长度小于 n，那么两个子串异或的结果一定小于 2^(n-1)。
3. 第一个子串选整个字符串时，第二个子串长度不超过 n-1，
   因此异或结果的最高位一定是 1，结果至少为 2^(n-1)。
4. 所以最优解一定可以让第一个子串为整个字符串。

二、如何确定第二个子串的长度？
1. 找到第一个 '0' 的下标 d。
2. 如果没有 '0'，说明整个字符串都是 '1'，
   此时第二个子串选任意一个 '1' 即可，异或结果最大。
3. 如果存在 '0'，令 k = n - d。
   此时后缀 s[d...n-1] 的长度为 k。
4. 第二个子串固定为长度 k，只需要枚举起点 i = 0...d-1。
   为什么？
   后缀的最高位是 '0'，而候选子串的最高位是 '1'，
   两者异或后最高位为 '1'。
   选择更短的子串无法得到更高的异或结果。

三、如何比较候选答案？
1. best：目前最优子串的起点，初始为 0。
2. i：当前正在检查的子串起点。
3. j：当前比较到子串的第几位。
4. cur：当前候选的异或结果在第 j 位的值。
5. old：目前最优候选的异或结果在第 j 位的值。

异或规则：
相同为 0，不同为 1。

从左往右逐位比较：
1. 如果 cur == old，继续比较下一位。
2. 如果 cur > old，说明当前候选更优，更新 best = i。
3. 如果 cur < old，说明当前候选更差，保留 best。
4. 一旦遇到第一位不同的位置，就可以停止比较。
   因为二进制数高位的权重大于所有低位之和。

四、为什么不用 long long？
字符串长度最多 5000，无法转换成 long long。
因此不实际计算异或后的整数，而是直接逐位比较异或结果。

五、输出下标
题目下标从 1 开始，C++ 字符串下标从 0 开始。
第一个子串： [1, n]
第二个子串： [best + 1, best + k]

时间复杂度：O(n^2)
空间复杂度：O(n)
*/

#include <bits/stdc++.h>
using namespace std;

void solve()
{
  string s;
  cin >> s;

  int n = s.size();
  int d = s.find('0');

  // 特殊情况：字符串全是 '1'
  if (d == -1)
  {
    cout << 1 << ' ' << n << ' ' << 1 << ' ' << 1 << '\n';
    return;
  }

  // 第二个子串的固定长度
  int k = n - d;

  // 初始认为起点为 0 的子串最优
  int best = 0;

  // 枚举第二个子串的起点
  for (int i = 1; i < d; ++i)
  {
    // 从左往右比较两个异或结果
    for (int j = 0; j < k; ++j)
    {
      // 当前候选的异或结果
      char cur = (s[d + j] != s[i + j]) ? '1' : '0';

      // 当前最优候选的异或结果
      char old = (s[d + j] != s[best + j]) ? '1' : '0';

      // 找到第一位不同的位置
      if (cur != old)
      {
        // 当前候选更大，更新最优起点
        if (cur > old)
          best = i;

        // 第一位不同已经决定大小，不必继续比较
        break;
      }
    }
  }

  // 输出两个子串的左右端点（下标从 1 开始）
  cout << 1 << ' ' << n << ' '
       << best + 1 << ' ' << best + k << '\n';
}

int main()
{
  ios::sync_with_stdio(false);
  cin.tie(nullptr);

  int t;
  cin >> t;

  while (t--)
    solve();

  return 0;
}

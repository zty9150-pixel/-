
/*
==================== 矩阵快速幂 ====================

一、适用场景

当题目要求计算递推数列的第 n 项，并且 n 非常大
（例如 n <= 1e18），普通 O(n) 递推无法完成时，
可以尝试矩阵快速幂。

适用前提：
1. 递推关系是固定的线性递推。
2. 能够构造固定维度的状态转移矩阵。
3. 需要快速计算矩阵的 n 次幂。

普通快速幂：
    计算 a^n % mod，时间复杂度 O(log n)。

矩阵快速幂：
    计算 A^n % mod，使用矩阵乘法替代普通乘法，
    时间复杂度 O(d^3 * log n)，d 为矩阵维度。


二、矩阵乘法

设：
    A 为 n * n 矩阵
    B 为 n * n 矩阵

则：
    C[i][j] = sum(A[i][k] * B[k][j])

即：
    左矩阵的第 i 行
    乘以右矩阵的第 j 列
    对应元素相乘后求和。

注意：
    矩阵乘法一般不满足交换律：
    A * B != B * A

取模时，每次累加都取模，防止数值过大。


三、矩阵快速幂原理

与普通快速幂完全相同：

while (b > 0)
{
    if (b & 1)
        ans = ans * A;

    A = A * A;
    b >>= 1;
}

区别：
    普通快速幂的乘法是数字乘法。
    矩阵快速幂的乘法是矩阵乘法。

为什么 ans 初始化为单位矩阵？

普通快速幂：
    ans = 1，因为 1 * a = a。

矩阵快速幂：
    ans = I，因为 I * A = A。

单位矩阵：
    主对角线元素为 1，其余元素为 0。

例如：
    1 0
    0 1


四、通用矩阵快速幂模板

*/

#include <bits/stdc++.h>
using namespace std;
using ll = long long;

const ll mod = 1e9 + 7;

struct Matrix
{
  int n;
  vector<vector<ll>> a;

  // 初始化 n*n 零矩阵
  // ident=true 时初始化为单位矩阵
  Matrix(int n, bool ident = false)
      : n(n), a(n, vector<ll>(n, 0))
  {
    if (ident)
    {
      for (int i = 0; i < n; ++i)
        a[i][i] = 1;
    }
  }
};

// 矩阵乘法：C = A * B
Matrix mul(const Matrix &A, const Matrix &B)
{
  int n = A.n;
  Matrix C(n);

  for (int i = 0; i < n; ++i)
  {
    for (int k = 0; k < n; ++k)
    {
      for (int j = 0; j < n; ++j)
      {
        C.a[i][j] =
            (C.a[i][j] + A.a[i][k] * B.a[k][j]) % mod;
      }
    }
  }

  return C;
}

// 矩阵快速幂：计算 A^b
Matrix qpow(Matrix A, ll b)
{
  Matrix ans(A.n, true); // 单位矩阵

  while (b > 0)
  {
    if (b & 1)
      ans = mul(ans, A);

    A = mul(A, A);
    b >>= 1;
  }

  return ans;
}

/*
五、经典例题：斐波那契数列

递推关系：
    f(n) = f(n-1) + f(n-2)

初始条件：
    f(0) = 0
    f(1) = 1

构造状态向量：
    [ f(n)   ]
    [ f(n-1) ]

因为：
    f(n)   = 1*f(n-1) + 1*f(n-2)
    f(n-1) = 1*f(n-1) + 0*f(n-2)

所以转移矩阵为：
    [ 1  1 ]
    [ 1  0 ]

即：
    [ f(n)   ]   [ 1  1 ] [ f(n-1) ]
    [ f(n-1) ] = [ 1  0 ] [ f(n-2) ]

记 A = [1 1; 1 0]，则：

    [ f(n)   ]       [ 1 ]
    [ f(n-1) ] = A^(n-1) [ 0 ]

所以：
    f(n) = A^(n-1)[0][0]

这里使用 0 下标。

注意：
    n = 0 时需要特判，返回 0。
    n >= 1 时，计算 A^(n-1) 即可。

六、斐波那契数列完整示例
*/

ll fib(ll n)
{
  if (n == 0)
    return 0;

  Matrix A(2);
  A.a[0][0] = 1;
  A.a[0][1] = 1;
  A.a[1][0] = 1;
  A.a[1][1] = 0;

  Matrix res = qpow(A, n - 1);

  return res.a[0][0];
}

/*
七、如何构造转移矩阵？

核心原则：

1. 先确定状态向量中需要保存哪些变量。
2. 用递推式表示新状态。
3. 将每个新状态写成旧状态的线性组合。
4. 每个新状态对应矩阵的一行。
5. 该行各列的系数，对应旧状态中各变量的系数。

例如：

    f(n) = 2*f(n-1) + 3*f(n-2) + 7

需要保存的状态：
    f(n)
    f(n-1)
    常数 1

状态向量：
    [ f(n)   ]
    [ f(n-1) ]
    [ 1      ]

转移矩阵：
    [ 2  3  7 ]
    [ 1  0  0 ]
    [ 0  0  1 ]

解释：

第一行：
    f(n) = 2*f(n-1) + 3*f(n-2) + 7*1

第二行：
    f(n-1) = 1*f(n-1) + 0*f(n-2) + 0*1

第三行：
    1 = 1

因此常数项也可以放进状态向量，
利用最后一行保证它始终保持为 1。

注意：
    这里的状态转移矩阵乘的是旧状态向量。
    构造时一定要确保状态顺序前后一致。


八、带 n、n^2 等多项式的递推

例如：

    f(n) = 2*f(n-1) + 3*f(n-2)
           + 3*n*n + 2*n + 7

仅保存 f(n-1)、f(n-2)、1 不够，
因为转移式还依赖 n 和 n^2。

于是扩展状态：

    [ f(n)   ]
    [ f(n-1) ]
    [ n*n    ]
    [ n      ]
    [ 1      ]

旧状态：

    [ f(n-1)     ]
    [ f(n-2)     ]
    [ (n-1)^2    ]
    [ n-1        ]
    [ 1          ]

利用：
    n*n = (n-1)^2 + 2*(n-1) + 1
    n = (n-1) + 1

以及：
    3*n*n + 2*n + 7
    = 3*(n-1)^2 + 8*(n-1) + 12

可以构造转移矩阵：

    [ 2  3  3  8  12 ]
    [ 1  0  0  0   0 ]
    [ 0  0  1  2   1 ]
    [ 0  0  0  1   1 ]
    [ 0  0  0  0   1 ]

这属于进阶拓展，暂时理解构造思想即可。


九、复杂度分析

设矩阵维度为 d，指数为 n。

矩阵乘法：
    O(d^3)

矩阵快速幂：
    O(d^3 * log n)

空间复杂度：
    O(d^2)

对于固定的 2*2、3*3 矩阵：
    时间复杂度可以视为 O(log n)。


十、常见错误

1. ans 初始化错误
   必须初始化为单位矩阵，不能初始化为全 1 矩阵。

2. 矩阵乘法下标错误
   C[i][j] 累加 A[i][k] * B[k][j]。

3. 矩阵乘法没有取模
   可能导致整数溢出。

4. 初始状态与指数不匹配
   如果从 [f(1), f(0)] 开始，
   求 f(n) 通常使用 A^(n-1)，而不是 A^n。

5. 忘记矩阵乘法不可交换
   A*B 和 B*A 通常不同。

6. 不是所有递推都适合矩阵快速幂
   需要能够构造固定维度的线性状态转移矩阵。

十一、最终记忆

普通快速幂：
    数字乘法 + 二进制拆分指数。

矩阵快速幂：
    矩阵乘法 + 二进制拆分指数。

真正的难点不是快速幂模板，
而是根据递推关系正确构造状态转移矩阵。
*/

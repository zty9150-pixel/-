/*
题目：Turtle and an Infinite Sequence
类型：位运算 / 按位或 OR / 二进制 / 区间按位或 / 构造
难度：CF 约 1400

一、题目大意
初始有一个无限序列 a[i] = i。
每秒所有元素同时更新：
a[i] = a[i-1] | a[i] | a[i+1]
其中 a[-1] = 0。

给定 n、m，求 m 秒后 a[n] 的值。

二、核心思路
1. 每经过一秒，位置 n 能影响到的范围向左右各扩展一格。
2. 因为按位或满足结合律、交换律、幂等律，
   所以 m 秒后的答案等价于：

   a[n] = L | (L+1) | ... | R

   L = max(0, n-m)
   R = n+m

3. 问题转化为：求连续整数区间 [L,R] 的按位或。

三、关键结论
对于连续整数区间 [L,R]：

1. 从最高位向最低位比较 L 和 R。
2. 最高位开始的相同二进制前缀保持不变。
3. 从第一个不同的二进制位开始，
   该位及后面的所有低位，按位或结果均为 1。

例如：
L = 10 = 01010
R = 13 = 01101
          ^
最高不同位是第 2 位。

区间按位或：
10 | 11 | 12 | 13 = 01111 = 15

四、为什么成立
假设 L、R 最高不同位为第 k 位。

由于 L < R：
1. 第 k 位之前的高位完全相同。
2. L 的第 k 位为 0，R 的第 k 位为 1。
3. 区间必然跨过第 k 位从 0 变成 1 的边界。
4. 边界前一个数的低 k 位全为 1。
5. 边界后的数第 k 位为 1。

因此第 k 位及以下所有位都能出现 1。
按位或之后，这些位全部为 1。

五、实现方法
从最高位向最低位枚举：

flag = false：还没有遇到不同位，保留原来的公共前缀。
flag = true ：已经遇到不同位，后面所有位都置为 1。

六、复杂度
时间复杂度：O(log(n+m))，本题最多遍历 32 位。
空间复杂度：O(1)。

七、易错点
1. 按位或是 |，不是逻辑或 ||。
2. 判断第 i 位：(x >> i) & 1。
3. 设置第 i 位：ans |= 1LL << i。
4. n-m 可能为负数，左端点必须取 max(0,n-m)。
5. n+m 最大为 2e9，使用 long long 更稳妥。
6. __builtin_clz(0) 是未定义行为，使用前必须判断。
7. 不能只计算 L | R，中间的整数也可能贡献新的 1。

八、适用题型
1. 连续整数区间的按位或。
2. 已知左右端点，求所有整数的 OR。
3. 利用二进制最高不同位构造答案。
4. 将多轮相邻状态更新转化为区间运算。

核心记忆：
连续区间按位或 = 保留左右端点的公共二进制高位前缀，
从最高不同位开始，所有低位全部置 1。
*/

#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
  ll n, m;
  cin >> n >> m;
  ll l = max(0LL, n - m);
  ll r = n + m;
  ll ans = 0;
  bool flag = false;
  for (int i = 31; i >= 0; --i)
  {
    int a = (l >> i) & 1;
    int b = (r >> i) & 1;
    if (a != b)
      flag = true;
    if (flag || a)
      ans |= 1LL << i;
  }
  cout << ans << '\n';
}

int main()
{
  ios::sync_with_stdio(false);
  cin.tie(nullptr);
  int t;
  cin >> t;
  while (t--)
    solve();
  return 0;
}
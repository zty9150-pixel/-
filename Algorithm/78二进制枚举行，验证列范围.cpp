
#include <bits/stdc++.h>
using namespace std;

/*
题目：J - Dividing Chocolate

一、题意

给定 H 行 W 列的 01 矩阵。

1 表示白格，0 表示黑格。

可以沿着格子的边界进行横切和竖切，
要求切割后的每个矩形中，1 的数量不超过 K。

求最少切割次数。

约束：
H <= 10
W <= 1000

二、核心思路

由于 H 很小，枚举所有横切方案。

相邻两行之间一共有 H - 1 个潜在横切位置，
因此横切方案数量为：

2^(H - 1) <= 512

固定横切方案后，再贪心地从左到右确定竖切位置。

三、横切方案的二进制枚举

mask 的第 i 位表示是否在第 i 行与第 i + 1 行之间切开。

group[i] 表示第 i 行所属的横向分组编号。
G 表示分组总数。

例如：

行号：   0  1 | 2  3
group：  0  0 | 1  1

此时 G = 2，分组编号为 0 和 1。

初始 G = 1，因为至少存在一个分组。

四、统计每列各分组的 1 的数量

遍历每一列 j，统计：

add[g] = 当前列在第 g 个横向分组中有多少个 1。

因为 H <= 10，直接遍历所有行统计即可，
不需要额外维护列前缀和。

如果 add[g] > K，说明当前横切方案无解。

原因：
即使只保留当前这一列，该分组中的 1 已经超过 K，
继续进行竖切也无法解决。

五、贪心确定竖切位置

cur[g] 表示当前竖向区间中，第 g 个分组累计的 1 的数量。

尝试加入当前列：

如果所有分组都满足
cur[g] + add[g] <= K

则可以加入当前列，更新 cur[g]。

如果任意分组超过 K：
必须在当前列之前切一刀。

然后：
1. 竖切次数加 1。
2. 当前竖向区间从当前列重新开始。
3. cur = add。

六、为什么贪心正确？

对于固定横切方案，每个分组中的 1 的数量只会随着列的增加而增加，
不会减少。

如果加入下一列后超过 K，那么当前区间不能再包含该列，
必须在该列之前切开。

尽可能延伸当前区间，不会增加竖切次数；
一旦无法延伸，立即切割就是最优选择。

因此，该贪心能够求出固定横切方案下的最少竖切次数。

七、正确性证明

1. 完备性：
   所有横切方案均被枚举。

2. 固定横切方案后：
   每个竖向区间的合法性由各分组中 1 的总数是否超过 K 决定。

3. 贪心最优：
   每次尽可能向右扩展区间；无法继续扩展时必须切割。
   因此得到该横切方案下最少的竖切次数。

4. 枚举所有横切方案并取最小值，
   得到全局最少切割次数。

八、复杂度

横切方案数量为 2^(H - 1)。

每个方案中，每列统计 H 个格子，并遍历 G 个分组。

时间复杂度：O(2^(H - 1) * H * W)
空间复杂度：O(H * W)

H <= 10，W <= 1000，因此可以通过。

九、易错点

1. 本题只有一组输入，没有测试组数 t。
2. mask 的位数是 H - 1，而不是 H。
3. G 表示分组数量，因此从 1 开始。
4. group 的编号从 0 到 G - 1。
5. 统计的是每个矩形中的 1 的总数，不是连续的 1 的长度。
6. 如果当前单列的 add[g] > K，该横切方案直接无效。
7. cuts 初始值为横切次数 popcount(mask)，之后累加竖切次数。
*/

int H, W, K;
vector<string> s;

void solve()
{
  cin >> H >> W >> K;

  s.resize(H);
  for (int i = 0; i < H; ++i)
    cin >> s[i];

  int ans = INT_MAX;

  // 枚举所有横切方案
  for (int mask = 0; mask < (1 << (H - 1)); ++mask)
  {
    vector<int> group(H);

    int G = 1;

    // 根据 mask 确定每一行所属的分组
    for (int i = 1; i < H; ++i)
    {
      group[i] = group[i - 1];

      if ((mask >> (i - 1)) & 1)
      {
        ++G;
        group[i] = G - 1;
      }
    }

    // 已经进行的横切次数
    int cuts = __builtin_popcount(mask);

    // 当前竖向区间内各分组的 1 的数量
    vector<int> cur(G, 0);

    bool ok = true;

    // 从左到右枚举每一列
    for (int j = 0; j < W; ++j)
    {
      vector<int> add(G, 0);

      // 统计当前列中各分组的 1 的数量
      for (int i = 0; i < H; ++i)
      {
        if (s[i][j] == '1')
          ++add[group[i]];
      }

      // 如果单列已经超出限制，该方案无解
      for (int g = 0; g < G; ++g)
      {
        if (add[g] > K)
          ok = false;
      }

      if (!ok)
        break;

      bool need_cut = false;

      // 判断当前列能否加入已有区间
      for (int g = 0; g < G; ++g)
      {
        if (cur[g] + add[g] > K)
          need_cut = true;
      }

      if (need_cut)
      {
        // 在当前列之前竖切
        ++cuts;

        // 当前区间从这一列重新开始
        cur = add;
      }
      else
      {
        // 可以合并，直接累计
        for (int g = 0; g < G; ++g)
          cur[g] += add[g];
      }
    }

    if (ok)
      ans = min(ans, cuts);
  }

  cout << ans << '\n';
}

int main()
{
  ios::sync_with_stdio(false);
  cin.tie(nullptr);

  // 注意：本题只有一组输入
  solve();

  return 0;
}

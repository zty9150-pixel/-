/*
题目：Interesting Sequence
类型：位运算 / 区间 AND / 二进制边界 / 贪心构造

一、题目大意

给定 n 和 x，寻找最小的 m，使得：

    n & (n+1) & ... & m = x

如果不存在这样的 m，输出 -1。

二、核心性质：区间 AND 只会清零，不会恢复

按位与的性质：

    1 & 1 = 1
    1 & 0 = 0
    0 & 0 = 0

因此：

1. 某一位只要遇到一个 0，最终 AND 的这一位就是 0。
2. 某一位如果在区间内始终为 1，最终 AND 的这一位就是 1。
3. 随着 m 增大，区间 AND 的每一位只能从 1 变成 0，
   不可能从 0 重新变成 1。

三、第一步：检查目标 x 是否可能

如果 x 某一位为 1，那么 n 的这一位必须为 1。

因为最终 AND 不可能产生 n 中不存在的 1。

所以必要条件为：

    (n & x) == x

如果不满足，直接输出 -1。

四、第二步：理解 pos 的含义

对于 n 中某个为 1 的二进制位 i：

    如果目标 x 的第 i 位为 0，
    就必须让区间中出现一个第 i 位为 0 的整数。

定义：

    pos_i = 从 n 开始，第 i 位第一次变成 0 的整数。

如果 m < pos_i：
    区间 [n, m] 中第 i 位一直为 1，
    所以最终 AND 的第 i 位仍然为 1。

如果 m >= pos_i：
    区间包含 pos_i，
    第 i 位就会变成 0。

五、如何计算 pos？

二进制第 i 位每隔 2^(i+1) 个整数重复一次完整周期。

每个周期中：

    前 2^i 个数：第 i 位为 0
    后 2^i 个数：第 i 位为 1

如果 n 的第 i 位为 1，
那么 n 位于这一周期的后半部分。

第 i 位下一次变成 0，
就在下一个 2^(i+1) 的整数倍处。

因此：

    pos_i = (floor(n / 2^(i+1)) + 1) * 2^(i+1)

C++ 写法：

    long long pos =
        ((n >> (i + 1)) + 1) << (i + 1);

例如：

    n = 13 = 01101

第 2 位为 1。

下一个 2^3 = 8 的整数倍是 16。

    13 = 01101
    14 = 01110
    15 = 01111
    16 = 10000

因此：

    pos_2 = 16

六、第三步：找到最小候选答案

对于所有满足：

    n_i = 1
    x_i = 0

的二进制位，这些位都必须清零。

每一位都要求：

    m >= pos_i

所以最小候选答案是：

    m = max(pos_i)

如果不存在需要清零的位，
则不需要扩大区间，答案候选值为 n。

七、第四步：检查是否误伤需要保留的 1

对于满足：

    n_i = 1
    x_i = 1

的位，必须始终保留为 1。

所以要求：

    m < pos_i

如果：

    m >= pos_i

说明区间已经跨过这个位第一次变成 0 的位置，
该位无法保留，因此无解。

注意：

如果 n_i = 0，那么最终该位必定为 0。
这种位不需要额外检查。

八、正确性证明

必要性：

1. 如果 (n & x) != x，
   则目标包含 n 中不存在的 1，必定无解。

2. 每个需要清零的位 i 都要求 m >= pos_i。
   因此任何合法答案都不能小于所有 pos_i 的最大值。

充分性：

令 m 为所有需要清零的位对应 pos_i 的最大值。

那么所有需要清零的位都已经遇到 0，
因此最终 AND 的这些位都是 0。

接着检查所有需要保留的位：

如果存在 m >= pos_i，
说明该位也已经遇到 0，无法保留，必须判定无解。

如果所有需要保留的位都满足 m < pos_i，
那么它们在整个区间中始终为 1。

因此最终 AND 的每一位都与 x 相同，
候选答案合法。

由于 m 是所有必须清零的位所要求的最小边界中的最大值，
所以它也是最小合法答案。

九、C++ 实现

    void solve()
    {
        long long n, x;
        cin >> n >> x;

        if ((n & x) != x)
        {
            cout << -1 << '\\n';
            return;
        }

        long long m = n;

        for (int i = 0; i <= 60; ++i)
        {
            long long bit = 1LL << i;

            if ((n & bit) && !(x & bit))
            {
                long long pos =
                    ((n >> (i + 1)) + 1) << (i + 1);

                m = max(m, pos);
            }
        }

        for (int i = 0; i <= 60; ++i)
        {
            long long bit = 1LL << i;

            if (!(n & bit))
                continue;

            long long pos =
                ((n >> (i + 1)) + 1) << (i + 1);

            if ((x & bit) && m >= pos)
            {
                cout << -1 << '\\n';
                return;
            }
        }

        cout << m << '\\n';
    }

十、复杂度

时间复杂度：O(61)，即 O(1)。
空间复杂度：O(1)。

十一、易错点

1. pos 表示第 i 位第一次变成 0 的整数，不是第一次变成 1。
2. pos 是下一个 2^(i+1) 的整数倍。
3. 需要清零的位取最大的 pos。
4. 需要保留的位必须满足 m < pos。
5. (n & x) == x 只是必要条件，还需要检查位之间的边界冲突。
6. 不需要枚举区间 [n, m] 中的所有整数。

十二、核心总结

每个需要清零的位，都对应一个必须跨过的二进制边界。

    先求所有必须清零的位的最大 pos；
    再检查这个边界是否清除了必须保留的 1。

关键思想：
区间 AND + 二进制周期 + 边界构造 + 贪心验证。
*/

#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    ll n, x;
    cin >> n >> x;

    if ((n & x) != x)
    {
        cout << -1 << '\n';
        return;
    }

    ll m = n;

    for (int i = 0; i <= 60; ++i)
    {
        ll bit = 1LL << i;
        if ((n & bit) && !(x & bit))
        {
            ll pos = ((n >> (i + 1)) + 1) << (i + 1);
            m = max(m, pos);
        }
    }

    for (int i = 0; i <= 60; ++i)
    {
        ll bit = 1LL << i;
        if (!(n & bit))
            continue;

        ll pos = ((n >> (i + 1)) + 1) << (i + 1);

        if ((x & bit) && m >= pos)
        {
            cout << -1 << '\n';
            return;
        }

        if (!(x & bit) && m < pos)
        {
            cout << -1 << '\n';
            return;
        }
    }

    cout << m << '\n';
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t;
    cin >> t;

    while (t--)
        solve();

    return 0;
}
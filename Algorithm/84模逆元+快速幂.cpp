/*
题目：D - Plant
考点：数学推导、快速幂、模逆元、位运算

一、题意与递推关系
每个三角形每年分裂成 4 个：
3 个与父三角形方向相同，1 个方向相反。

设：
U[n]：第 n 年朝上的三角形数量
D[n]：第 n 年朝下的三角形数量

初始状态：
U[0] = 1, D[0] = 0

递推关系：
U[n] = 3 * U[n-1] + D[n-1]
D[n] = U[n-1] + 3 * D[n-1]

二、寻找数学规律

1. 统计三角形总数：
每年每个三角形变成 4 个，因此：
U[n] + D[n] = 4^n

2. 统计朝上与朝下的数量差：
U[n] - D[n] = 2 * (U[n-1] - D[n-1])
因此：
U[n] - D[n] = 2^n

3. 联立两个等式：
U[n] + D[n] = 4^n
U[n] - D[n] = 2^n

两式相加：
2 * U[n] = 4^n + 2^n

最终公式：
U[n] = (4^n + 2^n) / 2

三、优化：只需要计算一次快速幂

因为：
4^n = (2^n)^2

设 b = 2^n mod mod，则：
4^n mod mod = b * b % mod

因此只需计算一次快速幂：
b = qpow(2, n)
a = b * b % mod

四、为什么不能直接使用位运算？

数学上：
2^n = 1 << n
4^n = 1 << (2*n)

但题目 n <= 10^18，远超 long long 的移位范围。
而且题目要求对 1e9+7 取模，
直接移位无法解决如此大的指数问题。

所以必须使用快速幂：
if (n & 1)  判断指数最低位是否为 1
n >>= 1     指数右移一位，相当于除以 2
a = a*a%mod 底数平方并取模

五、模逆元：为什么不能直接除以 2？

题目要求对 mod = 1e9+7 取模。
模运算中，取模之后不能直接进行普通整数除法。

寻找 x，使得：
2*x % mod = 1

因为 mod 是奇数：
inv2 = (mod + 1) / 2
     = 500000004

所以：
U[n] = (4^n + 2^n) / 2

在模意义下等价于：
ans = (a + b) % mod * inv2 % mod

注意：
inv2 是 2 的模逆元，不是普通整数除法。

六、完整代码
*/

#include <bits/stdc++.h>
using namespace std;
using ll = long long;

const ll mod = 1e9 + 7;
const ll inv2 = 500000004;

// 快速幂：计算 a^n % mod
// 时间复杂度 O(log n)，空间复杂度 O(1)
ll qpow(ll a, ll n)
{
  ll ans = 1;
  a %= mod;

  while (n > 0)
  {
    // 当前二进制位为 1，将当前底数乘入答案
    if (n & 1)
      ans = ans * a % mod;

    // 底数平方，准备计算下一位对应的幂
    a = a * a % mod;

    // 指数右移，相当于整除 2
    n >>= 1;
  }

  return ans;
}

int main()
{
  ios::sync_with_stdio(false);
  cin.tie(nullptr);

  ll n;
  cin >> n;

  // b = 2^n % mod
  ll b = qpow(2, n);

  // a = 4^n % mod
  // 4^n = (2^n)^2，因此不需要再进行一次快速幂
  ll a = b * b % mod;

  // U[n] = (4^n + 2^n) / 2
  // 模运算中除以 2，改为乘以 2 的模逆元
  ll ans = (a + b) % mod * inv2 % mod;

  cout << ans << '\n';

  return 0;
}

/*
七、复杂度分析

时间复杂度：O(log n)
空间复杂度：O(1)

八、本题总结

1. 先通过递推关系寻找总数和数量差。
2. 推导出 U[n] = (4^n + 2^n) / 2。
3. 利用 4^n = (2^n)^2，只计算一次快速幂。
4. 指数很大时不能直接使用 1LL << n。
5. 模运算中除以 2，使用模逆元 500000004。
*/
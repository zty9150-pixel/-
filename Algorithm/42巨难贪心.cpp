#include <bits/stdc++.h>
using namespace std;

using ll = long long;

//# 题目（中文，可直接复制）
// 给定 n 个矩形，每个矩形高度为 1。每个矩形的宽度都是 2 的幂（即可以写成 $2^x$，$x$ 为非负整数）。

// 再给一个宽度为 W 的箱子。注意 W 不一定是 2 的幂，并且 W 大于等于所有矩形的最大宽度。

// 求箱子的最小高度，使得能放下全部矩形。矩形放完后箱子可以留有空白。
// 不能旋转矩形；矩形之间不能重叠。

// ## 输入
// 第一行一个整数 t，表示测试用例组数。
// 每组测试用例两行：
// 第一行两个整数 n, W；
// 第二行 n 个整数 $w_1,w_2,\dots,w_n$，$w_i$ 是第 i 个矩形的宽度。
// 保证每个 $w_i$ 都是 2 的幂，且 $\max(w_i)\le W$。

// 所有测试用例的 n 总和不超过 $10^5$。

// ## 输出
// 每组输出一个整数：箱子的最小高度。


//************************************************************ */
/*
    check(k)：

    判断能不能让 k 个手办免费。

    贪心：
    如果要免费 k 个，那么一定选择：
    “能去商店的手办”中编号最大的 k 个。

    为什么？
    因为编号越大，免费掉它省的钱越多。
*/
bool check(const string& s, int k)
{
    int n = s.size();

    // used[i] = 1 表示第 i+1 个手办准备作为免费手办
    vector<int> used(n, 0);

    /*
        从后往前找最大的 k 个 s[i] = '1'

        例如：
        s = 1110001
        k = 2

        就选：
        7、3

        因为它们是所有可以购买的手办中最大的两个。
    */
    for (int i = n - 1; i >= 0; --i)
    {
        if (k > 0 && s[i] == '1')
        {
            used[i] = 1;
            --k;
        }
    }

    /*
        cur 表示：

        当前已经出现了多少个
        “可以拿来给后面的免费手办当陪买者”的手办。

        普通手办：
            cur++

        免费手办：
            需要消耗一个陪买者
            cur--

        如果 cur < 0：
            说明这个免费手办前面没有足够的手办
            给它当陪买者

            所以 k 个免费手办无法实现。
    */
    int cur = 0;

    for (int i = 0; i < n; ++i)
    {
        if (used[i])
        {
            // 当前手办要免费
            // 必须找一个之前的手办和它一起买
            --cur;

            if (cur < 0)
                return false;
        }
        else
        {
            // 当前手办不免费
            // 可以作为以后某个免费手办的陪买者
            ++cur;
        }
    }

    return true;
}

void solve()
{
    int n;
    cin >> n;

    string s;
    cin >> s;

    /*
        n = 1 时没有至少两个手办可以一起买，
        所以只能原价买第 1 个。
    */
    if (n == 1)
    {
        cout << 1 << '\n';
        return;
    }

    /*
        统计一共有多少个 s[i] = 1。

        免费手办必须是在某一天可以去商店购买的，
        所以最多只能免费这么多个。
    */
    int cnt1 = 0;

    for (char c : s)
    {
        if (c == '1')
            ++cnt1;
    }

    /*
        二分答案：

        k = 能免费购买的手办数量。

        如果 k 个可以免费，
        那么 k-1 个肯定也可以免费。

        所以具有单调性：

        可以 可以 可以 可以 不可以 不可以
                         ↑
                       最大 k
    */

    int l = 1;          // l 一定可行
    int r = cnt1 + 1;   // r 一定不可行

    while (r - l > 1)
    {
        int mid = (l + r) / 2;

        if (check(s, mid))
            l = mid;    // mid 可以免费
        else
            r = mid;    // mid 不可以免费
    }

    /*
        l 就是最多可以免费的手办数量。

        接下来真正计算答案。

        既然要免费 l 个，
        当然还是选择最大的 l 个 s[i] = 1。

        从后往前：
            如果 s[i] == 1 且还有免费名额
                → 这个手办免费
            否则
                → 正常付钱
    */

    ll ans = 0;

    for (int i = n - 1; i >= 0; --i)
    {
        if (s[i] == '1' && l > 0)
        {
            // 第 i+1 个手办免费
            --l;
        }
        else
        {
            // 正常购买，付 i+1 枚金币
            ans += i + 1;
        }
    }

    cout << ans << '\n';
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int T;
    cin >> T;

    while (T--)
    {
        solve();
    }

    return 0;
}
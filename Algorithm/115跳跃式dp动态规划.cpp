/*
题目：
    给定一个长度为 n 的数组 a。

    Beautiful 序列由若干个块组成：
    每个块的第一个元素表示该块后面还有多少个元素，
    随后必须紧跟对应数量的元素。

    例如：
    [3, 3, 4, 5, 2, 6, 1]

    可以分成：
    [3, 3, 4, 5] 和 [2, 6, 1]

    每次操作可以删除任意一个元素。
    求最少需要删除多少个元素，使序列变成 Beautiful。

思路：跳跃式 DP

    核心：
    每个位置都可以选择：
    1. 不作为新块的起点，直接跳过。
    2. 作为新块的起点，保留完整的一块。

    1. 状态设计：

       dp[i] 表示考虑原数组前 i 个位置，
       最多能够保留的元素数量。

       注意：
       dp[i] 表示前 i 个位置已经处理完毕，
       不代表第 i 个位置一定被保留，
       也不代表上一个块恰好结束在 i。

    2. 初始状态：

       dp[0] = 0;

       一个元素都不考虑，保留数量为 0。

    3. 状态转移：

       情况一：不选择当前位置作为块起点。

       直接继承之前的最优结果：

       dp[i] = max(dp[i], dp[i-1]);

       情况二：选择当前位置作为块起点。

       a[i] 表示当前块后面还需要 a[i] 个元素，
       因此当前块总长度为 a[i] + 1。

       当前块占据区间：

       [i, i + a[i]]

       如果 i + a[i] <= n，说明当前块完整存在。

       可以从前 i-1 个位置的最优结果转移：

       dp[i+a[i]] = max(
           dp[i+a[i]],
           dp[i-1] + a[i] + 1
       );

       注意这里使用 dp[i-1]：
       表示当前块开始之前，前面的元素已经处理完毕。
       前面不一定恰好有一个块结束于 i-1，
       中间未保留的元素可以直接删除。

    4. 最终答案：

       dp[n] 表示最多保留的元素数量。

       ans = n - dp[n];

正确性理解：

    每个块必须完整保留：
    如果选择 a[i] 作为块起点，
    就必须保留它后面的 a[i] 个元素。

    不需要枚举块内部的删除方案，
    因为块内部必须完整保留。

    选择当前块后，可以直接跳转到块的结束位置，
    不需要逐个处理块内部元素。

复杂度：

    时间 O(n)，每个位置只处理一次。
    空间 O(n)，用于保存 DP 状态。
*/

#include <bits/stdc++.h>
using namespace std;

void solve()
{
  int n;
  cin >> n;

  vector<int> a(n + 1), dp(n + 1, 0);

  for (int i = 1; i <= n; ++i)
    cin >> a[i];

  for (int i = 1; i <= n; ++i)
  {
    dp[i] = max(dp[i], dp[i - 1]);

    if (i + a[i] <= n)
    {
      dp[i + a[i]] = max(
          dp[i + a[i]],
          dp[i - 1] + a[i] + 1);
    }
  }

  cout << n - dp[n] << '\n';
}

int main()
{
  ios::sync_with_stdio(false);
  cin.tie(nullptr);

  int t;
  cin >> t;

  while (t--)
    solve();

  return 0;
}
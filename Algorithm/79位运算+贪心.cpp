
/*
题目：XOR-distance
核心算法：位运算 + 贪心
核心目标：选择 0 <= x <= r，使 |(a ^ x) - (b ^ x)| 最小

一、位权分析
1. 二进制整数可以表示为各位位权之和：
   A = sum(a[i] * 2^i)
   B = sum(b[i] * 2^i)

2. 两数的差可以直接按位权展开，不需要模拟借位：
   A - B = sum((a[i] - b[i]) * 2^i)

3. 如果 a[i] == b[i]，无论 x[i] 是 0 还是 1，
   异或后这一位仍然相同，对差值的贡献始终为 0。

4. 如果 a[i] != b[i]：
   a[i] = 1, b[i] = 0:
       x[i] = 0，贡献为 +2^i
       x[i] = 1，贡献为 -2^i

   a[i] = 0, b[i] = 1:
       x[i] = 0，贡献为 -2^i
       x[i] = 1，贡献为 +2^i

二、最高不同位
1. 先交换 a、b，保证 a >= b。
2. 找到 a、b 最高的二进制不同位 k。
3. 此时必然有 a[k] = 1，b[k] = 0。
4. 可以固定 x[k] = 0：
   如果原来 x[k] = 1，将 x 的第 k 位及以下所有位翻转，
   可以使最终差值反号，绝对值不变，同时得到更小的 x。
   因此总存在一个最优解，使 x[k] = 0。

5. 最高不同位贡献 +2^k。
   所有低位的贡献绝对值之和最多为 2^k - 1，
   所以低位无法改变最终差值的正负。

三、低位贪心
1. 最高不同位已经固定为 0，接下来从高位向低位遍历。
2. 只考虑满足 a[i] = 1、b[i] = 0 的位置。
3. 对于这样的位：
   x[i] = 0 时贡献 +2^i；
   x[i] = 1 时贡献 -2^i。
   因此选择 x[i] = 1，可以让差值减少 2^(i+1)。

4. 为什么从高位向低位？
   第 i 位的收益为 2^(i+1)，大于所有更低位收益之和。
   因此优先考虑更高的有效位。

5. 如何满足 x <= r？
   如果当前 x 的第 i 位还没有设置，尝试加入 2^i：
       x + 2^i <= r：可以选择，执行 x += 2^i；
       x + 2^i > r：跳过这一位。
   注意：允许 x == r，因此判断条件是 <=，不是 <。

四、正确性证明
1. 最高不同位固定为 0，不会损失最优解。
2. 相同位以及 a[i] = 0、b[i] = 1 的位置无需设置为 1，
   因为这样不会改善差值。
3. 对于 a[i] = 1、b[i] = 0 的位置，选择 1 可以减少差值。
4. 更高位的收益大于所有更低位收益之和，因此按高位优先
   的顺序选择合法位，不会因为低位的选择得到更优结果。
5. 每次选择都检查 x + 2^i <= r，保证最终 x <= r。

五、复杂度
时间复杂度：O(log(max(a, b, r)))，最多遍历约 61 位。
空间复杂度：O(1)。

六、代码模板
*/

#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
  ll a, b, r;
  cin >> a >> b >> r;

  if (a < b)
    swap(a, b);

  ll x = 0;
  bool first = true;

  for (int i = 60; i >= 0; --i)
  {
    ll bit = 1LL << i;

    // 相同位不影响差值
    if ((a & bit) == (b & bit))
      continue;

    // 第一次遇到不同位，就是最高不同位，固定 x[i] = 0
    if (first)
    {
      first = false;
      continue;
    }

    // 只有 a[i] = 1、b[i] = 0 时，设置 x[i] = 1 才能减小差值
    if ((a & bit) && !(b & bit))
    {
      // 检查加入这一位后是否仍满足 x <= r
      if (x + bit <= r)
        x += bit;
    }
  }

  cout << abs((a ^ x) - (b ^ x)) << '\n';
}

int main()
{
  ios::sync_with_stdio(false);
  cin.tie(nullptr);

  int T;
  cin >> T;

  while (T--)
    solve();

  return 0;
}

/*
题目：所有长度为 k 的子数组 OR 相同
类型：位运算 / 按位或 / 逐位考虑 / 连续段统计 / 单调性

一、题目大意

给定长度为 n 的数组 a。

寻找最小的正整数 k，使得：

所有长度为 k 的连续子数组，
按位或 OR 的结果完全相同。

例如：

    a = [1, 0, 2]

当 k = 1：

    [1] -> 1
    [0] -> 0
    [2] -> 2

结果不同。

当 k = 2：

    [1,0] -> 1
    [0,2] -> 2

结果不同。

当 k = 3：

    [1,0,2] -> 3

只有一个区间，满足要求。

因此答案为 3。

二、核心转化：子数组 OR 与整个数组 OR 的关系

设整个数组的按位或为：

    S = a[1] | a[2] | ... | a[n]

关键结论：

所有长度为 k 的子数组 OR 相同

等价于：

所有长度为 k 的子数组 OR 都等于 S。

三、为什么这个结论成立？

首先：

任意子数组 OR 都不可能包含 S 中不存在的二进制位。

假设所有长度为 k 的子数组 OR 都相同，
其结果为 T。

考虑 S 中任意一个为 1 的二进制位 b。

由于 S 的第 b 位为 1，
说明整个数组至少存在一个元素，其第 b 位为 1。

而数组中的每个元素，
都至少属于一个长度为 k 的连续子数组。

因此，至少存在一个长度为 k 的子数组，
其 OR 的第 b 位为 1。

又因为所有长度为 k 的子数组 OR 都等于 T，
所以 T 的第 b 位必然为 1。

这对 S 中所有为 1 的二进制位都成立。

同时 T 不可能存在 S 中没有的 1。

因此：

    T = S

所以原题等价于：

寻找最小的 k，
使得任意长度为 k 的区间 OR 都等于整个数组 OR。

四、按位独立考虑

按位或的每个二进制位互不影响。

因此可以把原问题拆成最多 20 个独立的 01 数组问题。

例如：

    a = [1, 0, 2]

二进制：

    第 0 位：1 0 0
    第 1 位：0 0 1

整个数组 OR 为：

    1 | 0 | 2 = 3 = 11

因此每个合法区间都必须同时包含：

    第 0 位的 1
    第 1 位的 1

五、核心结论：统计最长连续 0

对于某一个二进制位，假设：

    1 0 0 0 1 0 0 1

要求任意长度为 k 的区间，
都至少包含一个 1。

观察：

    1 [0 0 0] 1 0 0 1

最长连续 0 的长度为 3。

如果 k <= 3：

    存在长度为 k 的全 0 区间。

这个区间在当前二进制位上的 OR 为 0，
因此不满足要求。

如果 k > 3：

    任意长度为 k 的区间都不可能全部为 0。

因此每个区间在当前二进制位上的 OR 都为 1。

所以：

    k > 最长连续 0 的长度

即：

    k_min = 最长连续 0 的长度 + 1

六、为什么需要跳过全为 0 的二进制位？

假设某一位：

    0 0 0 0 0

这一位在整个数组 OR 中为 0。

无论 k 取多少，
所有子数组 OR 的这一位都为 0。

因此这一位不会对答案产生限制。

只有整个数组中至少出现过一次 1 的二进制位，
才需要统计最长连续 0。

七、最终答案

设 mx[b] 表示第 b 位最长连续 0 的长度。

对于至少出现过一个 1 的二进制位：

    k >= mx[b] + 1

由于所有二进制位都必须满足条件：

    ans = max(mx[b] + 1)

如果整个数组全为 0：

    ans = 1

八、实现方法

枚举每个二进制位 b：

    for (int b = 0; b < 20; ++b)

对于每一位，遍历整个数组：

    cnt：当前连续 0 的长度
    mx ：最长连续 0 的长度
    tag：这一位是否出现过 1

如果当前位为 1：

    cnt = 0
    tag = true

如果当前位为 0：

    cnt++
    mx = max(mx, cnt)

遍历结束后：

    if (tag)
        ans = max(ans, mx + 1)

九、复杂度

由于 a[i] < 2^20，只需要枚举 20 位。

时间复杂度：O(20n)
空间复杂度：O(n)

十、AND 变形

如果题目改为：

所有长度为 k 的子数组 AND 相同。

则可以使用完全对称的方法。

OR：
    统计最长连续 0。
    只考虑至少出现过一个 1 的二进制位。

AND：
    统计最长连续 1。
    只考虑至少出现过一个 0 的二进制位。

对于 AND：

    k_min = 最长连续 1 的长度 + 1

最终对所有有效二进制位取最大值。

十一、单调性

如果长度为 k 的所有区间 OR 都相同，
那么长度为 k+1 的所有区间 OR 也相同。

因为合法区间必须包含整个数组 OR 中的全部有效位。

区间长度增加后，
不会丢失已经包含的二进制位。

因此：

    k 不合法 -> 可能继续不合法
    k 合法   -> 更大的 k 一定合法

所以也可以使用二分答案。

但统计最长连续 0 可以直接求出临界值，
不需要二分。

十二、数学理解：集合覆盖

可以把整数的每个二进制位看成一个集合元素。

例如：

    5 = 101 -> {0,2}
    6 = 110 -> {1,2}

按位或相当于集合并集：

    5 | 6 = 111 -> {0,1,2}

因此：

子数组 OR = 整个数组 OR

等价于：

子数组包含整个数组出现过的全部二进制位。

这本质上是一个集合覆盖问题。

十三、核心总结

1. 按位 OR 可以拆成独立的二进制位考虑。
2. 所有子数组 OR 相同，等价于都等于整个数组 OR。
3. 每个有效二进制位都必须在所有长度为 k 的区间中出现。
4. 任意长度为 k 的区间包含 1，
   等价于不存在长度为 k 的连续全 0 区间。
5. 因此只需要统计最长连续 0 的长度。

核心公式：

    ans = 1 + max(有效二进制位的最长连续 0 长度)

关键思想：
按位独立考虑 + 区间条件转化 + 最长连续段统计。
*/
#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve()
{
    int n;
    cin >> n;
    vector<int> a(n + 1);
    for (int i = 1; i <= n; ++i)
        cin >> a[i];

    int ans = 1;

    for (int k = 19; k >= 0; --k)
    {
        int cnt = 0, sum = 0;
        bool tag = false;

        for (int i = 1; i <= n; ++i)
        {
            if ((a[i] >> k) & 1)
            {
                cnt = 0;
                tag = true;
            }
            else
            {
                cnt++;
                sum = max(cnt, sum);
            }
        }

        if (tag)
            ans = max(ans, sum + 1);
    }

    cout << ans << '\n';
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t;
    cin >> t;

    while (t--)
        solve();

    return 0;
}
#include <bits/stdc++.h>
using namespace std;

using ll = long long;

/*
题目：手办购买问题
有一家商店卖手办。一共有 n 个手办，第 i 个手办价格为 i 金币，只能在第 i 天到第 n 天购买。
一共有 n 天。给定字符串 s，s[i]为1代表第 i+1 天可以去商店，0代表不能去。

每次进店，可以购买任意多个当前已经上架的手办，不能重复购买同一个手办。
优惠规则：同一天购买至少2个手办，则最贵的那个手办免费。

Monocarp 需要买下全部 n 个手办，每个恰好买一次。求最少花费。

输入：
第一行 t 测试用例。
每组：
第一行 n
第二行字符串 s，长度n。
保证 s[n-1] = '1'，第n天一定可以进店。
所有测试用例 n总和 ≤ 4e5。

输出：
每组输出最小花费。
*/


//************************************************************ */
/*
    check(k)：

    判断能不能让 k 个手办免费。

    贪心：
    如果要免费 k 个，那么一定选择：
    “能去商店的手办”中编号最大的 k 个。

    为什么？
    因为编号越大，免费掉它省的钱越多。
*/
bool check(const string& s, int k)
{
    int n = s.size();

    // used[i] = 1 表示第 i+1 个手办准备作为免费手办
    vector<int> used(n, 0);

    /*
        从后往前找最大的 k 个 s[i] = '1'

        例如：
        s = 1110001
        k = 2

        就选：
        7、3

        因为它们是所有可以购买的手办中最大的两个。
    */
    for (int i = n - 1; i >= 0; --i)
    {
        if (k > 0 && s[i] == '1')
        {
            used[i] = 1;
            --k;
        }
    }

    /*
        cur 表示：

        当前已经出现了多少个
        “可以拿来给后面的免费手办当陪买者”的手办。

        普通手办：
            cur++

        免费手办：
            需要消耗一个陪买者
            cur--

        如果 cur < 0：
            说明这个免费手办前面没有足够的手办
            给它当陪买者

            所以 k 个免费手办无法实现。
    */
    int cur = 0;

    for (int i = 0; i < n; ++i)
    {
        if (used[i])
        {
            // 当前手办要免费
            // 必须找一个之前的手办和它一起买
            --cur;

            if (cur < 0)
                return false;
        }
        else
        {
            // 当前手办不免费
            // 可以作为以后某个免费手办的陪买者
            ++cur;
        }
    }

    return true;
}

void solve()
{
    int n;
    cin >> n;

    string s;
    cin >> s;

    /*
        n = 1 时没有至少两个手办可以一起买，
        所以只能原价买第 1 个。
    */
    if (n == 1)
    {
        cout << 1 << '\n';
        return;
    }

    /*
        统计一共有多少个 s[i] = 1。

        免费手办必须是在某一天可以去商店购买的，
        所以最多只能免费这么多个。
    */
    int cnt1 = 0;

    for (char c : s)
    {
        if (c == '1')
            ++cnt1;
    }

    /*
        二分答案：

        k = 能免费购买的手办数量。

        如果 k 个可以免费，
        那么 k-1 个肯定也可以免费。

        所以具有单调性：

        可以 可以 可以 可以 不可以 不可以
                         ↑
                       最大 k
    */

    int l = 1;          // l 一定可行
    int r = cnt1 + 1;   // r 一定不可行

    while (r - l > 1)
    {
        int mid = (l + r) / 2;

        if (check(s, mid))
            l = mid;    // mid 可以免费
        else
            r = mid;    // mid 不可以免费
    }

    /*
        l 就是最多可以免费的手办数量。

        接下来真正计算答案。

        既然要免费 l 个，
        当然还是选择最大的 l 个 s[i] = 1。

        从后往前：
            如果 s[i] == 1 且还有免费名额
                → 这个手办免费
            否则
                → 正常付钱
    */

    ll ans = 0;

    for (int i = n - 1; i >= 0; --i)
    {
        if (s[i] == '1' && l > 0)
        {
            // 第 i+1 个手办免费
            --l;
        }
        else
        {
            // 正常购买，付 i+1 枚金币
            ans += i + 1;
        }
    }

    cout << ans << '\n';
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int T;
    cin >> T;

    while (T--)
    {
        solve();
    }

    return 0;
}
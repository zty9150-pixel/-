/*
题目：01 字符串反转
类型：贪心 / 构造 / 奇偶性 / 字典序最大化 / 字符串

一、题目大意

给定一个长度为 n 的 01 字符串 s，需要恰好执行 k 次操作。

每次选择一个位置 i，使除了位置 i 以外的所有位置反转：
0 -> 1
1 -> 0

要求：
1. 最终字符串的字典序最大。
2. 输出最终字符串。
3. 输出每个位置被选择的次数 f[i]。

二、核心思路：利用奇偶性转化操作

假设位置 i 被选择了 f[i] 次。

由于总共进行了 k 次操作，而选中位置 i 时它不会反转，
所以位置 i 实际被反转的次数为：

    k - f[i]

最终状态：

    s'[i] = s[i] ^ ((k - f[i]) % 2)

由于只关心奇偶性，因此不需要模拟每次操作。

三、分类讨论

情况一：k 为偶数

    k % 2 = 0

此时：

    s'[i] = s[i] ^ (f[i] % 2)

结论：
1. 位置 i 被选择偶数次，最终状态不变。
2. 位置 i 被选择奇数次，最终状态反转。

因此：
从左往右，优先选择原本为 0 的位置，使其变成 1。


情况二：k 为奇数

    k % 2 = 1

此时：

    s'[i] = s[i] ^ 1 ^ (f[i] % 2)

结论：
1. 位置 i 被选择偶数次，最终状态反转。
2. 位置 i 被选择奇数次，最终状态不变。

因此：
从左往右，优先选择原本为 1 的位置，保护它不被反转。

四、统一贪心策略

令：

    p = k % 2

假设每个位置都没有被选择，那么最终状态为：

    s[i] ^ p

从左往右考虑每个位置。

如果默认状态为 0：

    (s[i] ^ p) == 0

那么可以花费一次操作选择该位置，
使其最终状态变成 1。

如果默认状态为 1，则不需要操作。

统一判断：

    if ((bit ^ p) == 0 && k > 0)

五、为什么只处理前 n-1 个位置？

题目要求恰好执行 k 次操作。

为了保证所有操作都能分配出去：

1. 从左往右贪心处理前 n-1 个位置。
2. 尽可能让这些位置最终变成 1。
3. 将剩余的所有操作次数分配给最后一个位置。

即：

    f[n-1] = 剩余操作次数

最后一个位置根据剩余次数的奇偶性计算最终状态。

这样既能保证操作次数恰好为 k，
又能使最终字符串的字典序最大。

六、贪心正确性

字典序比较优先考虑最靠前的不同位置。

例如：

    11100 > 11011

虽然第二个字符串后面有更多的 1，
但是第一个字符串在更靠前的位置出现了 1。

因此：

1. 优先保证第 0 位最大。
2. 再保证第 1 位最大。
3. 依次处理到第 n-2 位。
4. 最后一位负责吸收剩余操作。

由于每个位置的最终状态只与 f[i] 的奇偶性有关，
而同一位置可以被选择多次，
所以剩余操作可以全部分配给最后一个位置。

这保证了贪心构造的合法性和最优性。

七、复杂度

时间复杂度：O(n)
空间复杂度：O(n)

八、易错点

1. 每次操作反转的是除选中位置外的所有位置。
2. 必须恰好执行 k 次，不能提前停止。
3. k 可能很大，需要使用 long long。
4. 必须保存原始 k 的奇偶性，不能使用不断减少的 k。
5. 最后一个位置必须单独处理。
6. 输出每个位置被选择的次数，而不是反转次数。

九、核心总结

多次反转操作 -> 转化为奇偶性问题。

    最终状态 = 原始状态 ^ ((k - f[i]) % 2)

字典序最大化 -> 从左往右贪心。

操作次数必须用完 -> 最后一个位置兜底。

关键思想：
奇偶性转化 + 字典序贪心 + 末尾兜底构造。
*/
#include <bits/stdc++.h>
using namespace std;
using ll = long long;

const int N = 2e5 + 10;

int n, k;
string s;

void solve()
{
    cin >> n >> k >> s;
    vector<int> vis(n, 0);
    int m = k;
    string ans(n, '0');
    for (int i = 0; i < n; ++i)
    {
        if (k % 2)
        {
            if (s[i] == '1' && m)
            {
                ans[i] = '1';
                m--;
                vis[i]++;
            }
            else if (s[i] == '0')
            {
                ans[i] = '1';
            }
            else
                ans[i] = '0';
        }
        else
        {
            if (s[i] == '0' && m)
            {
                ans[i] = '1';
                m--;
                vis[i]++;
            }
            else if (s[i] == '1')
            {
                ans[i] = '1';
            }
            else
                ans[i] = '0';
        }
    }
    if (m % 2)
    {
        ans[n - 1] = '0';
        vis[n - 1] += m;
    }
    else
        vis[n - 1] += m;
    cout << ans << '\n';
    for (int i = 0; i < n; ++i)
        cout << vis[i] << ' ';
    cout << '\n';
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    int t;
    cin >> t;
    while (t--)
    {
        solve();
    }
    return 0;
}
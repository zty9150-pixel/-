/*
============================================================
J. 序列查询
核心：有限前缀维护 + 操作历史记录 + 二分 + 取模映射
============================================================

一、题意

有两种操作：

操作 1：在序列末尾添加数字 x。

操作 2：取当前序列前 l 个元素，
        将这段前缀复制 c 次，追加到末尾。

最后查询若干个位置上的数字。

问题：
操作 2 可能让序列长度迅速增长，
无法真正构造完整序列。

------------------------------------------------------------
二、关键性质：只需要保存前 K 个数字
------------------------------------------------------------

题目保证：

1 <= l <= 1e5

也就是说，每次操作 2 只会复制前 1e5 个数字以内的内容。

因此：

K = 1e5

只需要维护最终序列的前 K 个数字即可。

定义：

a：保存真实序列的前 K 个元素。

构造过程中：
- 类型 1：如果 a.size() < K，直接添加 x。
- 类型 2：从 a 的前 l 个元素中复制 c 份，
          直到 a.size() == K 就停止。

为什么这样可行？

因为所有操作都只在末尾追加元素，
不会修改已有元素。

因此最终序列的前 K 个元素，
就是整个构造过程中维护的前 K 个元素。

而且题目保证 l <= K，
所以每次复制所需的前缀一定在 a 中。

------------------------------------------------------------
三、记录每次操作后的真实序列长度
------------------------------------------------------------

定义：

len[i]：执行完第 i 次操作后，真实序列的长度。

初始：

len[0] = 0

类型 1：

len[i] = len[i-1] + 1

类型 2：

len[i] = len[i-1] + l*c

注意：
len 记录的是真实序列长度，
不是缓存数组 a 的长度。

使用 long long：
因为真实序列长度可能非常大。

------------------------------------------------------------
四、查询位置 p 的处理
------------------------------------------------------------

情况一：p <= K

直接从缓存中读取：

a[p-1]

因为 a 保存了最终序列的前 K 个数字。

情况二：p > K

缓存中没有这个位置，需要反向寻找它的来源。

------------------------------------------------------------
五、二分定位操作
------------------------------------------------------------

由于每次操作都会增加序列长度：

len[i] > len[i-1]

所以 len 严格递增。

利用 lower_bound 找到：

第一个满足 len[i] >= p 的操作。

即：

i = lower_bound(len.begin()+1, len.end(), p)

为什么找到这个操作？

因为：
len[i-1] < p <= len[i]

说明查询位置 p 是在第 i 次操作中首次被构造出来的。

接下来分两种情况。

------------------------------------------------------------
六、如果第 i 次操作是类型 1
------------------------------------------------------------

类型 1 只会在末尾添加一个数字 x。

由于：

len[i-1] < p <= len[i]

并且：

len[i] = len[i-1]+1

因此 p 一定是本次新增的位置。

直接返回：

op[i].x

------------------------------------------------------------
七、如果第 i 次操作是类型 2
------------------------------------------------------------

这是本题最重要的部分。

设：

old = len[i-1]

l = op[i].l

原序列：

[原来的所有元素]

新增部分：

[前缀][前缀]...[前缀]

每份前缀长度为 l。

查询位置 p 一定在新增部分中。

1. 计算它在新增部分中的 0-based 偏移：

offset = p - old - 1

2. 利用取模找到它在某一份前缀中的位置：

offset % l

3. 转换成从 1 开始的编号：

pos = (p-old-1)%l+1

最终公式：

pos = (p-len[i-1]-1)%l+1

为什么要 -1 和 +1？

因为：
- offset 从 0 开始编号。
- 原始前缀中的位置从 1 开始编号。

------------------------------------------------------------
八、为什么只需要映射一次？
------------------------------------------------------------

由公式：

pos = (p-old-1)%l+1

可以得到：

1 <= pos <= l

而题目保证：

l <= 1e5 = K

因此：

pos <= K

所以映射后的位置一定在缓存 a 中。

直接返回：

a[pos-1]

不需要继续 DFS，也不需要再次二分。

------------------------------------------------------------
九、复杂度分析
------------------------------------------------------------

设 K = 1e5。

读取操作并记录长度：O(m)

构造缓存：
最多向 a 中添加 K 个元素。
每次操作最多产生常数级额外循环开销。
总计 O(m+K)。

每次查询：
- p <= K：O(1)
- p > K：二分 O(log m)，取模 O(1)

总时间复杂度：

O(m + K + n*log(m))

空间复杂度：

O(m+K)

------------------------------------------------------------
十、容易出错的地方
------------------------------------------------------------

1. 必须先读取 m，再创建 vector<Node> op(m+1)。
2. len 必须使用 long long，不能使用 int。
3. a 只保存前 K 个元素，不是完整序列。
4. 类型 2 必须复制原始前缀，不能复制整个当前序列。
5. a[k] 读取时先保存到局部变量，再 push_back，
   避免 vector 扩容导致引用失效。
6. lower_bound 找的是第一个 len[i] >= p 的位置。
7. 类型 2 的取模是对 l 取模，不是对 old 取模。
8. pos 是从 1 开始的编号，访问 a 时要使用 a[pos-1]。
9. 查询位置超过 K 时，必须先定位产生它的操作。
10. m、len、p、l*c 等涉及长度的变量使用 long long。

============================================================
*/

#include <bits/stdc++.h>
using namespace std;
using ll = long long;

const int K = 1e5;

struct Node
{
  int type;
  ll x, l, c;
};

void solve()
{
  int m;
  cin >> m;

  vector<Node> op(m + 1);
  vector<ll> len(m + 1, 0);

  // 只保存真实序列的前 K 个数字
  vector<ll> a;

  // 第一部分：记录操作，并截断构造前 K 个数字
  for (int i = 1; i <= m; ++i)
  {
    cin >> op[i].type;

    if (op[i].type == 1)
    {
      cin >> op[i].x;

      len[i] = len[i - 1] + 1;

      if (a.size() < K)
        a.push_back(op[i].x);
    }
    else
    {
      cin >> op[i].l >> op[i].c;

      ll l = op[i].l;
      ll c = op[i].c;

      // 记录真实序列长度
      len[i] = len[i - 1] + l * c;

      // 将前缀复制 c 次，直到缓存达到 K
      for (int j = 0; j < c && a.size() < K; ++j)
      {
        for (int k = 0; k < l && a.size() < K; ++k)
        {
          // 先保存，再追加，避免 vector 扩容影响引用
          ll val = a[k];
          a.push_back(val);
        }
      }
    }
  }

  // 第二部分：回答查询
  int n;
  cin >> n;

  while (n--)
  {
    ll p;
    cin >> p;

    // 情况一：查询位置在缓存范围内
    if (p <= K)
    {
      cout << a[p - 1] << ' ';
      continue;
    }

    // 情况二：二分找到第一次产生位置 p 的操作
    int i = lower_bound(
                len.begin() + 1,
                len.end(),
                p) -
            len.begin();

    // 类型 1：位置 p 就是新添加的数字
    if (op[i].type == 1)
    {
      cout << op[i].x << ' ';
    }
    else
    {
      // 类型 2：逆向映射到原始前缀
      ll old = len[i - 1];
      ll l = op[i].l;

      ll pos = (p - old - 1) % l + 1;

      // pos <= l <= K，一定能在缓存中找到
      cout << a[pos - 1] << ' ';
    }
  }

  cout << '\n';
}

int main()
{
  ios::sync_with_stdio(false);
  cin.tie(nullptr);

  solve();

  return 0;
}